"""View: docs/architecture/components.md (Mermaid diagram + table)."""
from __future__ import annotations

import re

from ...domain.components import ComponentGraph

FILE = "docs/architecture/components.md"
SHAPES = {"box": ('["', '"]'), "db": ('[("', '")]'), "queue": ('[["', '"]]'), "hex": ('{{"', '"}}')}
LABEL_LINE_RE = re.compile(r'^\s+(\w+)(?:\[\(|\[\[|\{\{|\[)"([^"<]+)<br/>([^"]*)"')


def labels_from(md: str | None) -> dict[str, str]:
    """Labels already in a committed components.md: {id: label} (lets a re-run keep them)."""
    return {m.group(1): m.group(3) for l in (md or "").splitlines() if (m := LABEL_LINE_RE.match(l))}


def mermaid(graph: ComponentGraph, labels: dict[str, str]) -> str:
    def box(c, indent: str) -> str:
        a, b = SHAPES[c.shape]
        return f"{indent}{c.id}{a}{c.name}<br/>{graph.label_for(c, labels)}{b}"

    out = ["flowchart LR"]
    out += [box(c, "    ") for c in graph.components if not c.is_storage]
    storage = [c for c in graph.components if c.is_storage]
    if storage:
        out += ['    subgraph infra["Infrastructure"]', *(box(c, "        ") for c in storage), "    end"]
    for l in graph.links:
        arrow = "-.->" if l.dotted else "-->"
        out.append(f"    {l.source} {arrow}{f'|{l.label}|' if l.label else ''} {l.target}")
    return "\n".join(out)


def render(graph: ComponentGraph, labels: dict[str, str]) -> str:
    rows = []
    for c in graph.components:
        where = f"`{c.path}`" if c.path else c.tech or c.kind
        libs = ", ".join(graph.project_refs.get(c.id, [])) or "—"
        rows.append(f"| {c.name} | {graph.label_for(c, labels)} | {where} | {graph.talks_to(c.id) or '—'} | {libs} |")
    return "\n".join([
        "# Components", "",
        f"Generated by Brieflet from `{graph.apphost}`, the project files and the HTTP/gRPC client registrations. "
        "Change the code, not this file. Solid arrow = calls / uses, dotted = gets a URL (auth).", "",
        "```mermaid", mermaid(graph, labels), "```", "",
        "| Box | What it is | Where | Talks to | Uses libraries |",
        "|---|---|---|---|---|",
        *rows, ""])
