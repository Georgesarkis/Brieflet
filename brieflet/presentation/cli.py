"""brieflet init <repo> [--llm ollama] [--out DIR] [--plan] [--yes] [--no-footer]

Local (Ollama) is free and the default. A paid plugin backend prints an estimate first and only sends with --yes.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from ..application.generate_brief import NoComponentsFound
from ..application.ports import ModelError, RepoUnreadable


def parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(prog="brieflet")
    sub = ap.add_subparsers(dest="cmd", required=True)
    i = sub.add_parser("init", help="write AI_CONTEXT.md + diagram + decision records for a repo")
    i.add_argument("repo")
    i.add_argument("--llm", default="ollama", help="model backend: ollama (local, default) or an installed plugin")
    i.add_argument("--small-model")
    i.add_argument("--write-model")
    i.add_argument("--out", help="write here instead of into the repo (e.g. a benchmark arm folder)")
    i.add_argument("--rev", default="HEAD")
    i.add_argument("--plan", action="store_true", help="show what would run + cost, call no model")
    i.add_argument("--yes", action="store_true", help="allow paid model calls (plugin backends)")
    i.add_argument("--no-footer", action="store_true",
                   help='leave out the "Generated by Brieflet" line (or set BRIEFLET_FOOTER=0)')
    return ap


def main(argv=None) -> int:
    from ..bootstrap import brief_controller, language_model
    a = parser().parse_args(argv)
    try:
        model = language_model(a.llm, a.small_model, a.write_model)
    except ModelError as e:
        print(e)
        return 2
    try:
        job = brief_controller(Path(a.repo), model, Path(a.out) if a.out else None, a.rev,
                               footer=False if a.no_footer else None)
        plan = job.plan()
    except (RepoUnreadable, NoComponentsFound) as e:
        print(e)
        return 2
    print(f"{len(plan.graph.components)} components, {len(plan.candidates)} decision candidates, {len(plan.calls)} model calls "
          f"({a.llm}: small={model.small}, write={model.write}).")
    for n in plan.graph.notes:
        print(f"note: {n}")
    if not model.paid:
        print("Cost: $0 (local model).")
    else:
        est = model.estimate_usd(plan.calls)
        print("Cost estimate (worst case): " + (f"${est:.3f}" if est is not None else "unknown (no price for this model)"))
    if a.plan:
        return 0
    if model.paid and not a.yes:
        print("Refused: this backend costs money. Re-run with --yes after reading the estimate.")
        return 2
    print(json.dumps(job.run(plan).as_dict(), indent=1))
    return 0
